import { readFile, writeFile } from 'node:fs/promises';

const directory = new URL('./', import.meta.url);
const read = (path) => readFile(new URL(path, directory), 'utf8');
const [manifestText, css, script, logo] = await Promise.all([
  read('manifest.json'),
  read('portal.css'),
  read('portal.js'),
  readFile(new URL('college-logo.png', directory)),
]);
const manifest = JSON.parse(manifestText);
const matches = manifest.content_scripts[0].matches.map((match) => `// @match        ${match}`);
const metadata = [
  '// ==UserScript==',
  `// @name         ${manifest.name}`,
  '// @namespace    urn:math-portal:classic-notices',
  `// @version      ${manifest.version}`,
  `// @description  ${manifest.description}`,
  ...matches,
  '// @run-at       document-idle',
  '// @noframes',
  '// @grant        GM_addStyle',
  '// @grant        GM_registerMenuCommand',
  '// ==/UserScript==',
].join('\n');

await writeFile(
  new URL('math-portal.user.js', directory),
  [
    metadata,
    '// Generated by build-userscript.mjs.',
    `const smsPortalLogoUrl = 'data:image/png;base64,${logo.toString('base64')}';`,
    `GM_addStyle(${JSON.stringify(css)});`,
    "GM_registerMenuCommand('打开数院四栏版', () => location.assign('https://mathsmart.pku.edu.cn/schedule#four-panels'));",
    script,
  ].join('\n\n'),
);
